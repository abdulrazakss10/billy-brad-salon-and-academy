// Helper functions
export function getServicesByCategory(categoryId) {
  return SERVICES.filter((s) => s.category === categoryId);
}

export function getServiceBySlug(slug) {
  return SERVICES.find((s) => s.slug === slug);
}

export function getFeaturedServices() {
  return SERVICES.filter((s) => s.featured);
}

// Returns other services worth showing on a service detail page:
// prefers same-category services first, then tops up with featured
// services from elsewhere so there's always a useful set to show.
export function getRelatedServices(service, limit = 3) {
  if (!service) return [];

  const sameCategory = SERVICES.filter(
    (s) => s.category === service.category && s.id !== service.id
  );

  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }

  const fillers = SERVICES.filter(
    (s) =>
      s.id !== service.id &&
      s.featured &&
      !sameCategory.some((sc) => sc.id === s.id)
  );

  return [...sameCategory, ...fillers].slice(0, limit);
}

export function getServicesByAudience(audience) {
  return SERVICES.filter((s) => s.audience.includes(audience));
}

export function searchServices(query) {
  const q = query.toLowerCase();
  return SERVICES.filter(
    (s) =>
      s.name.toLowerCase().includes(q) ||
      s.category.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q) ||
      s.keywords.some((k) => k.toLowerCase().includes(q))
  );
}
